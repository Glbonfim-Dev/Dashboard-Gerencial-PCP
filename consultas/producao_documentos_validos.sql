-- Aplicado sobre a grade original: documentos válidos e devoluções referenciadas.
DOCUMENTOS_VALIDOS AS (
    SELECT N.COD_EMPRESA,N.MODELO,N.SERIE,N.SUB_SERIE,N.NUMERO,
           N.NUMERO_NFSE,N.DT_EMISSAO,N.CLIENTE
    FROM TNOTA_FISCAL N CROSS JOIN PARAMETROS P
    WHERE COALESCE(N.CANCELADA, 0) = 0
      AND N.DT_EMISSAO >= P.DATA_INICIO
      AND N.DT_EMISSAO < P.DATA_FIM + INTERVAL '1 DAY'
      AND (N.NFE_COD_STATUS = '100' OR
           (COALESCE(N.MODELO, '') NOT IN ('55', '65') AND N.NFE_COD_STATUS IS NULL))
),
DEVOLUCOES_REFERENCIADAS AS (
    SELECT DISTINCT D.COD_EMPRESA, D.MODELO, D.SERIE, D.SUB_SERIE, D.NUMERO,
           R.AUT_ AS ITEM_DEVOLUCAO, R.COD_PRODUTO, R.QTDE,
           O.MODELO AS MODELO_ORIGEM, O.SERIE AS SERIE_ORIGEM,
           O.SUB_SERIE AS SUB_SERIE_ORIGEM, O.NUMERO AS NUMERO_ORIGEM
    FROM DOCUMENTOS_VALIDOS D
    JOIN TNOTA_FISCAL_ITEM R
      ON (R.COD_EMPRESA,R.MODELO,R.SERIE,R.SUB_SERIE,R.NUMERO_NF) =
         (D.COD_EMPRESA,D.MODELO,D.SERIE,D.SUB_SERIE,D.NUMERO)
    JOIN TNOTA_FISCAL_NFREF F
      ON (F.COD_EMPRESA,F.MODELO,F.SERIE,F.SUB_SERIE,F.NUMERO_NF) =
         (D.COD_EMPRESA,D.MODELO,D.SERIE,D.SUB_SERIE,D.NUMERO)
    JOIN DOCUMENTOS_VALIDOS O
      ON O.COD_EMPRESA = F.COD_EMPRESA
     AND O.MODELO = F.NFREF_MODELO AND O.SERIE = F.NFREF_SERIE
     AND O.SUB_SERIE = F.NFREF_SUB_SERIE AND O.NUMERO = F.NFREF_NUMERO_NF
     AND O.DT_EMISSAO::DATE = F.NFREF_DT_EMISSAO::DATE
    WHERE (COALESCE(R.NATUREZA_OP,'') ILIKE '%DEVOL%'
           OR CAST(R.CFOP AS TEXT) IN ('1201','1202','2201','2202','3201','3202'))
      AND R.QTDE > 0
      AND EXISTS (
          SELECT 1 FROM TNOTA_FISCAL_ITEM X
          WHERE (X.COD_EMPRESA,X.MODELO,X.SERIE,X.SUB_SERIE,X.NUMERO_NF) =
                (O.COD_EMPRESA,O.MODELO,O.SERIE,O.SUB_SERIE,O.NUMERO)
            AND X.COD_PRODUTO = R.COD_PRODUTO
      )
),
-- Uma devolução com várias origens do mesmo produto não permite atribuição segura.
DEVOLUCOES_UNIVOCAS AS (
    SELECT * FROM (
        SELECT R.*, COUNT(*) OVER (
            PARTITION BY COD_EMPRESA,MODELO,SERIE,SUB_SERIE,NUMERO,ITEM_DEVOLUCAO
        ) AS ORIGENS FROM DEVOLUCOES_REFERENCIADAS R
    ) R WHERE ORIGENS = 1
),
VOLUMES_DEVOLVIDOS AS MATERIALIZED (
    SELECT COD_EMPRESA, MODELO_ORIGEM, SERIE_ORIGEM, SUB_SERIE_ORIGEM,
           NUMERO_ORIGEM, COD_PRODUTO, SUM(QTDE) AS QTDE_DEVOLVIDA
    FROM DEVOLUCOES_UNIVOCAS
    GROUP BY COD_EMPRESA,MODELO_ORIGEM,SERIE_ORIGEM,SUB_SERIE_ORIGEM,NUMERO_ORIGEM,COD_PRODUTO
),
ITENS_COM_SALDO AS (
    SELECT I.COD_EMPRESA,I.MODELO,I.SERIE,I.SUB_SERIE,I.NUMERO_NF,
           I.AUT_,I.COD_ORCAMENTO,I.GUID_ORCAMENTO,I.COD_OS,I.COD_PRODUTO,
           I.PRODUTO,I.QTDE,I.TP_MOVIMENTO_DEPOSITO,
           CASE WHEN I.QTDE IS NULL THEN NULL ELSE GREATEST(0, I.QTDE - GREATEST(0,
               COALESCE(D.QTDE_DEVOLVIDA,0) - COALESCE(SUM(I.QTDE) OVER (
                   PARTITION BY I.COD_EMPRESA,I.MODELO,I.SERIE,I.SUB_SERIE,I.NUMERO_NF,I.COD_PRODUTO
                   ORDER BY I.AUT_ ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING
               ),0))) END AS QTDE_REMANESCENTE
    FROM TNOTA_FISCAL_ITEM I
    JOIN DOCUMENTOS_VALIDOS N
      ON (I.COD_EMPRESA,I.MODELO,I.SERIE,I.SUB_SERIE,I.NUMERO_NF) =
         (N.COD_EMPRESA,N.MODELO,N.SERIE,N.SUB_SERIE,N.NUMERO)
    LEFT JOIN VOLUMES_DEVOLVIDOS D
      ON (I.COD_EMPRESA,I.MODELO,I.SERIE,I.SUB_SERIE,I.NUMERO_NF,I.COD_PRODUTO) =
         (D.COD_EMPRESA,D.MODELO_ORIGEM,D.SERIE_ORIGEM,D.SUB_SERIE_ORIGEM,D.NUMERO_ORIGEM,D.COD_PRODUTO)
    WHERE I.TP_MOVIMENTO_DEPOSITO = 1
      AND COALESCE(I.NATUREZA_OP,'') NOT ILIKE '%DEVOL%'
      AND COALESCE(CAST(I.CFOP AS TEXT),'') NOT IN ('1201','1202','2201','2202','3201','3202')
),
ITENS_PRODUCAO_VALIDOS AS MATERIALIZED (
    SELECT I.*, CASE WHEN I.QTDE IS NULL THEN 1
                    ELSE I.QTDE_REMANESCENTE::DOUBLE PRECISION / NULLIF(I.QTDE,0) END AS FATOR_REMANESCENTE
    FROM ITENS_COM_SALDO I WHERE I.QTDE_REMANESCENTE > 0 OR I.QTDE IS NULL
),
